# 블레싱 가/나 RAG 전체(현재 정본 15 + 미반영 추가초안 7)를 상태별로 한 폴더에 정리·복사
"""
현재 스토어에 올라간 정본 15 + 아직 미반영인 추가 초안 7(신규5·교체2)을
상태가 드러나는 구조로 모은다. 업로드(스토어 반영)는 별도 단계 — 여기선 파일 정리만.
"""

import shutil
from pathlib import Path

RAGDIR = Path("/Users/woosung/문서/docs/RAG 데이터")
SRC_정본 = RAGDIR / "블레싱_가나_RAG정본_15문서_2026-06-12"  # 이번 세션에서 검증·생성한 정본 15
SRC_초안 = RAGDIR / "스토어_업로드_초안"
DEST = RAGDIR / "블레싱_가나_RAG데이터_2026-06-12"

# 추가 초안 7건의 상태 (README + 문서 머리말 근거)
DRAFTS = {
    "가정공과금_안내_2022.md": ("신규", "공과금 5종 금액·연혁. 문서에 '2022.03 기준' 캐비앗 내장. 금액 현행 여부 관리자 확인 권장(계좌 의도적 제외)."),
    "데스밸리특별성염_전수및사용_2024-019호.md": ("신규", "공문 2024-019호. 확인 필요 없음."),
    "삼위기대_안내.md": ("신규", "공문 2025-133호 발췌 + 말씀선집. 확인 필요 없음."),
    "천일국_예복예물_안내.md": ("교체", "기존 정본 천일국_예복예물_안내.md 교체본(KH_가치v3 신규사실 병합). 매장 위치는 미반영. replace_document 로 교체."),
    "축복헌금_환불규정.md": ("교체", "기존 정본 축복헌금_환불규정.md 교체본(출처 1줄 갱신). 선택 사항."),
    "식구가정관리_출생성화개명_안내_2021.md": ("조건부", "2021 구버전. 문서에 '최신 하나로 확인' 유의 내장. 추가 여부 결정 필요."),
    "2세-1세축복_2세가정편성_지침_2020-282호.md": ("조건부", "구공문. 일부 항목은 259호로 대체(문서에 대체 고지 내장). 추가 자체를 결정(보류 가능)."),
}


def main():
    if DEST.exists():
        shutil.rmtree(DEST)
    d_정본 = DEST / "01_현재_스토어_정본_15"
    d_초안 = DEST / "02_미반영_추가초안_7"
    d_정본.mkdir(parents=True)
    d_초안.mkdir(parents=True)

    # 정본 15 (매니페스트 제외 복사)
    n1 = 0
    for p in SRC_정본.iterdir():
        if p.is_file() and not p.name.startswith("_"):
            shutil.copy2(p, d_정본 / p.name)
            n1 += 1

    # 추가 초안 7
    n2 = 0
    for fname in DRAFTS:
        src = SRC_초안 / fname
        if src.exists():
            shutil.copy2(src, d_초안 / fname)
            n2 += 1
        else:
            print(f"  ! 초안 누락: {fname}")

    # 통합 매니페스트
    lines = [
        "# 블레싱 가/나 RAG 데이터 — 전체 정리 (2026-06-12)",
        "",
        "블레싱 가(id5)·나(id3)는 동일한 RAG 문서 셋을 쓴다. 이 폴더는 **현재 스토어에 올라간 정본**과",
        "**아직 반영되지 않은 추가 초안**을 상태별로 모은 것이다. 업로드(스토어 반영)는 별도 단계다.",
        "",
        f"## 01_현재_스토어_정본_15 ({n1}개)",
        "File Search 스토어에 실제 올라가 있는 문서(파일명+바이트크기로 검증). 가/나 동일.",
        "이미 RAG로 작동 중인 정본이다.",
        "",
        f"## 02_미반영_추가초안_7 ({n2}개) — 스토어에 아직 없음",
        "2026-06-10 작성·원문 대조 검증 완료했으나 미업로드. 신규 5 + 교체 2.",
        "",
        "| 파일 | 성격 | 메모 |",
        "|---|---|---|",
    ]
    for fname, (kind, note) in DRAFTS.items():
        lines.append(f"| {fname} | {kind} | {note} |")
    lines += [
        "",
        "## 업로드(스토어 반영) 시 주의",
        "- 교체 2종(예복예물·환불)은 같은 이름 정본을 **replace_document**(삭제 후 재업로드)로 교체.",
        "- 신규 5종은 bot_id=3·5 메타데이터로 **upload_document** 추가.",
        "- 스토어는 가/나(및 다른 봇)가 공유 — 반영 시 두 봇 모두 영향. dev/live 동일 스토어.",
        "- 조건부 2종(식구가정관리·282호)·가정공과금 금액 현행성은 사용자 결정 후 반영.",
    ]
    (DEST / "_매니페스트.md").write_text("\n".join(lines), encoding="utf-8")

    print(f"완료 → {DEST}")
    print(f"  01_현재_스토어_정본_15: {n1}개")
    print(f"  02_미반영_추가초안_7: {n2}개")

    # 정본-only 구버전 폴더 제거(이 세션 생성, 상위 폴더로 흡수됨)
    if SRC_정본.exists():
        shutil.rmtree(SRC_정본)
        print(f"  (정리) 구 정본폴더 제거: {SRC_정본.name}")


if __name__ == "__main__":
    main()
