# 그룹핑 키에서 털어낼 것 — 공백·문장부호·밑줄
_NOISE_RE = re.compile(r"[\s\W_]+", re.UNICODE)

# 봇이 스스로 「못 답한다」고 말한 표현.
#
# **`strict_mode._REFUSAL_RE` 를 쓰면 안 된다.** 그건 **관리자가 쓴 FAQ 거절문**을 가리는
# 자라서 "답변 드리기 어렵습니다" 모양을 본다. 반면 여기서 잴 것은 **봇이 시스템 프롬프트를
# 따라 낸 출력**이고, 라이브 봇 11 프롬프트가 시키는 문구는 "확인되지 않습니다" 다.
# 실제로 라이브 어시스턴트 2,268건에 `_REFUSAL_RE` 를 대면 14건(0.6%)만 걸리고
# 「확인되지 않」 30건을 통째로 놓친다. 처음에 그걸 재사용했다가 E2E 에서 잡혔다.
#
# 라이브 2,268건으로 보정한 결과 이 패턴은 **65건(2.9%)** 을 잡는다. 관리자가 훑어서
# 처리할 만한 밀도다. 거짓양성 쪽으로 기울여 놨다 — 기록일 뿐 답변을 막지 않기 때문이다
# (사용자에게 보이는 문구는 1층뿐이다).
#
# `[^.]{0,N}` 로 문장 경계를 못 넘게 막은 것이 핵심이다. `.{0,16}` 로 두면
# "신앙적 **안내**자 역할… 너무 **어렵**게 생각하지 마시고" 같은 격려문이 거절로 잡힌다
# (`_REFUSAL_RE` 의 실제 거짓양성이다).
_SELF_REFUSAL_RE = re.compile(
    r"확인되지\s*(?:는\s*)?않|확인할\s*수\s*없|확인이\s*어렵|"
    r"규정집에\s*(?:는\s*)?(?:없|나와\s*있지\s*않|명시되지\s*않)|"
    r"명시된\s*(?:내용|문서|조항|규정)[^.]{0,10}(?:없|않)|"
    # `답변할` 만 알면 **라이브 D-1 ver2 가 가장 많이 내는 거절문을 통째로 놓친다.**
    # 그 봇 프롬프트 원칙 8번이 "규정집 이외의 내용에는 **답할 수 없습니다**" 라고
    # 문구까지 지정해 두는데 여기에 `변` 이 없다. 봇 29(라이브 복제본) 96셀 측정에서
    # 놓친 거절문 18건 중 17건이 이 한 문장이었다.
    r"답(?:변)?할\s*수?\s*없|"
    r"(?:안내|답변|말씀)\s*(?:을|해|해서)?\s*(?:드리기|드릴|드리지)[^.]{0,6}(?:어렵|없|못)",
    re.IGNORECASE,
)


def normalize_question(text: str) -> str:
    """빈도 집계용 그룹핑 키.

    `ops_facts_service._normalize` 와 같은 규약(NFKC + casefold)에 문장부호까지 턴다.
    "축복 헌금 얼마예요?" 와 "축복헌금 얼마예요" 가 한 줄로 묶여야 하기 때문이다.

    라이브 실측: 사용자 메시지 2,268건 중 **74%가 이 정규화 후 정확히 중복**이다
    (고유 1,195 / 2회 이상 603). 임베딩 클러스터링 없이 이 화면이 성립하는 근거다.
    """
    return _NOISE_RE.sub("", unicodedata.normalize("NFKC", text or "").casefold())


def is_self_refusal(answer: str) -> bool:
    """봇이 스스로 못 답한다고 말했는가.

    근거 충분성을 **추정하지 않는다.** 봇의 출력을 문자열로 읽을 뿐이다 — 검색 점수로
    답변 가능성을 재려던 시도는 세 번 다 실패했고, 이건 그것과 다른 종류의 판정이다.

    이 신호가 관리자 화면을 채우는 주력이다(라이브 2,268건 중 65건 = 2.9%).
    """
    return bool(_SELF_REFUSAL_RE.search(answer or ""))


@dataclass
class RetrievalTrace:
    """근거 조달 과정에서 관찰된 것. `_retrieve_and_generate` 가 채워서 돌려준다.

    `answer_with_wiki` 가 `tuple[RAGResponse, Retrieved]` 를 돌려주는데 지금은 두 번째를
    버린다. 점수가 살아 있는 유일한 줄이라 여기로 받는다 — 다만 **점수는 안 쓴다.**
    쓰는 것은 `units`(2층 판정기가 읽을 원문)와 `reasons`(관찰된 사실)뿐이다.

    ⚠ **모델이 받는 근거는 `units` 만이 아니다.** `answer_with_wiki` 는 `raw`·`raw_budget`
    에서 `# 규정 원문`(units) 뒤에 `# 참고 정리`(`_wiki_block`)를 함께 넣는다. 위키 페이지의
    `## 사실` 에는 `> 원문 인용` 이 붙어 있어(생성 규약) **units 에 없는 조문의 원문이
    프롬프트에 들어간다.** 그것을 정확히 인용한 답변을 units 하고만 대조하면 「지어냄」이
    된다 — replay R0085 는 제17조를 축자 재현하고 정확히 인용했는데 units 에 reg-17 이 없어
    `fabricated_loc=['조17']` 로 찍혔다. 그래서 페이지가 실어 온 근거도 같이 남긴다.

    **기록만 한다 — 게이트 판정은 아직 이것을 읽지 않는다.** 읽게 하면 라이브 차단량이
    바뀌므로 STEP 3 파일럿 동결 하에서는 손대지 않는다.
    """

    reasons: list[str] = field(default_factory=list)
    units: list[SourceUnit] = field(default_factory=list)
    # 위키 페이지 슬러그와 그 페이지들이 실어 온 원문 참조. 본문은 넣지 않는다(규칙 1).
    pages: list[str] = field(default_factory=list)
    page_src_ids: list[str] = field(default_factory=list)

    def mark(self, reason: str) -> None:
        if reason not in self.reasons:
            self.reasons.append(reason)
